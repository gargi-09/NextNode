"""Generate cypher/seed.cypher from ontology/skills.json.

    python scripts/build_seed.py          # writes cypher/seed.cypher
    python scripts/build_seed.py --check  # exits 1 if the file is out of date

The output is deterministic (sorted), so it is safe to commit and diff.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.graph.ontology import load_ontology  # noqa: E402

SEED_PATH = ROOT / "cypher" / "seed.cypher"


def _rows(items: list[dict]) -> str:
    return ",\n".join("  " + json.dumps(i, ensure_ascii=False) for i in items)


def _cypher_literal(rows: str) -> str:
    # JSON object keys are quoted; Cypher map keys must not be
    import re
    return re.sub(r'"(\w+)":', r"\1:", rows)


def build() -> str:
    o = load_ontology()
    domains = [{"name": k, "description": v} for k, v in sorted(o.domains.items())]
    skills = sorted(
        ({"key": s.key, "name": s.name, "category": s.category, "level": s.level}
         for s in o.skills.values()),
        key=lambda r: r["key"],
    )
    prereqs = sorted(
        ({"from": p.source, "to": p.target, "strength": p.strength} for p in o.prerequisites),
        key=lambda r: (r["from"], r["to"]),
    )
    belongs = sorted(
        ({"skill": s.name, "domain": d} for s in o.skills.values() for d in s.domains),
        key=lambda r: (r["skill"], r["domain"]),
    )

    return f"""// ─── GENERATED by scripts/build_seed.py from ontology/skills.json (version {o.version}) ───
// Do not edit by hand: change the JSON and re-run the script.
// Idempotent: nodes are MERGEd on their unique name, then properties are SET.
// Run cypher/constraints.cypher first.

// ─── Domains ───

UNWIND [
{_cypher_literal(_rows(domains))}
] AS row
MERGE (d:Domain {{name: row.name}})
SET d.description = row.description;

// ─── Skills ───

UNWIND [
{_cypher_literal(_rows(skills))}
] AS row
MERGE (s:Skill {{name: row.name}})
SET s.key      = row.key,
    s.category = row.category,
    s.level    = row.level;

// ─── Prerequisite chains ───

UNWIND [
{_cypher_literal(_rows(prereqs))}
] AS row
MATCH (a:Skill {{name: row.from}})
MATCH (b:Skill {{name: row.to}})
MERGE (a)-[r:PREREQUISITE_OF]->(b)
SET r.strength = row.strength;

// ─── Skill → domain membership ───

UNWIND [
{_cypher_literal(_rows(belongs))}
] AS row
MATCH (s:Skill {{name: row.skill}})
MATCH (d:Domain {{name: row.domain}})
MERGE (s)-[:BELONGS_TO]->(d);
"""


if __name__ == "__main__":
    content = build()
    if "--check" in sys.argv:
        current = SEED_PATH.read_text(encoding="utf-8") if SEED_PATH.exists() else ""
        if current != content:
            print("cypher/seed.cypher is out of date — run scripts/build_seed.py")
            sys.exit(1)
        print("cypher/seed.cypher is up to date")
    else:
        SEED_PATH.write_text(content, encoding="utf-8")
        print(f"wrote {SEED_PATH.relative_to(ROOT)}")
